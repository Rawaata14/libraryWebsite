/*
=========================================================
api.js

תיאור הקובץ:
הגדרות משותפות לתקשורת בין ה-Frontend ל-Backend.

הקובץ מרכז את כתובת שרת ה-Backend במקום אחד,
כדי למנוע כתיבה חוזרת של אותה כתובת בקומפוננטות
ובדפים שונים.
=========================================================
*/

/*
---------------------------------------------------------
API_BASE_URL

תפקיד:
מכילה את כתובת הבסיס של שרת ה-Backend.

אם קיים VITE_API_URL בקובץ הסביבה:
נעשה שימוש בערך שלו.

בסביבת הפיתוח המקומית:
נעשה שימוש ב-http://localhost:8000.
---------------------------------------------------------
*/
export const API_BASE_URL =
  import.meta.env.VITE_API_URL || "http://localhost:8000";

/*
---------------------------------------------------------
buildApiUrl

תפקיד:
מקבלת נתיב API ומחזירה כתובת מלאה לשרת.

דוגמה:
buildApiUrl("/user/login")
מחזירה:
http://localhost:8000/user/login
---------------------------------------------------------
*/
export function buildApiUrl(path) {
  const normalizedPath = path.startsWith("/") ? path : `/${path}`;

  return `${API_BASE_URL}${normalizedPath}`;
}
