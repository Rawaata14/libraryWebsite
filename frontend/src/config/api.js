/*
=========================================================
api.js

תיאור הקובץ:
הגדרות משותפות לתקשורת בין ה-Frontend ל-Backend.

הקובץ מרכז את כתובת שרת ה-Backend במקום אחד,
ומאפשר תקשורת בסביבה המקומית ובגישה מרחוק
באמצעות מנגנון ה-Proxy של Vite.
=========================================================
*/

/*
---------------------------------------------------------
API_BASE_URL

תפקיד:
מכילה את כתובת הבסיס של שרת ה-Backend.

אם קיים VITE_API_URL בקובץ הסביבה:
נעשה שימוש בערך שלו.

אחרת:
נעשה שימוש בנתיב היחסי /api,
והבקשות מועברות לשרת באמצעות Vite Proxy.
---------------------------------------------------------
*/
export const API_BASE_URL = import.meta.env.VITE_API_URL || "/api";

/*
---------------------------------------------------------
buildApiUrl

תפקיד:
מקבלת נתיב API ומחזירה כתובת בקשה לשרת.

פרמטרים:
path - נתיב הבקשה.

ערך מוחזר:
כתובת הבקשה בהתאם לכתובת הבסיס המוגדרת.

דוגמה:
buildApiUrl("/user/login")
מחזירה כברירת מחדל:
 /api/user/login
---------------------------------------------------------
*/
export function buildApiUrl(path) {
  const normalizedPath = path.startsWith("/") ? path : `/${path}`;

  return `${API_BASE_URL}${normalizedPath}`;
}
