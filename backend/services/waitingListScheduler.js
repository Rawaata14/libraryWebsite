/*
=========================================================
waitingListScheduler.js

תיאור הקובץ:
מתזמן התחזוקה האוטומטית של רשימות ההמתנה.

אחריות:
- הפעלת בדיקה מחזורית של השאלות שהסתיימו.
- החזרת ספרים למלאי.
- בדיקת הצעות שפג תוקפן.
- העברת הצעה למשתמש הבא בתור.
- מניעת הרצה כפולה של אותו מחזור תחזוקה.

למה הקובץ נוצר:
פעולות רשימת ההמתנה צריכות להתבצע גם כאשר
אף משתמש אינו לוחץ על כפתור באתר.

לדוגמה:
- הצעה שפגה צריכה לעבור לבא בתור.
- ספר צריך לחזור למלאי כשזמן השימוש מסתיים.
=========================================================
*/

const waitingListService = require("./waitingListService");

/*
משתנה השומר את מזהה ה-setInterval.

השימוש בו מונע יצירה של כמה מתזמנים
אם פונקציית ההפעלה נקראת יותר מפעם אחת.
*/
let scheduler = null;

/*
מציין אם מחזור תחזוקה כבר פועל.

הבדיקה חשובה משום שמחזור אחד עשוי להימשך
יותר מדקה. בלי ההגנה, המחזור הבא עלול
להתחיל לפני שהקודם הסתיים.
*/
let isRunning = false;

/*
---------------------------------------------------------
runWaitingListMaintenance

תפקיד:
מריצה מחזור תחזוקה יחיד של רשימות ההמתנה.

בכל מחזור:
1. מאתרים השאלות ספרים שהסתיימו.
2. מחזירים את העותקים למלאי.
3. מציעים ספרים למשתמשים הבאים בתור.
4. מאתרים הצעות ספר או מקום שפג תוקפן.
5. מעבירים את ההצעה למשתמש הבא.

אם מחזור קודם עדיין פועל:
הפונקציה מסתיימת ללא הרצה נוספת.
---------------------------------------------------------
*/
async function runWaitingListMaintenance() {
  /*
  מניעת חפיפה בין שני מחזורי תחזוקה.
  */
  if (isRunning) {
    return;
  }

  isRunning = true;

  try {
    /*
    סיום השאלות ספרים שהגיע זמן החזרתן.

    לאחר החזרת הספר למלאי, השירות בודק
    אם קיים משתמש שממתין לספר.
    */
    await waitingListService.releaseFinishedLoansAndOfferBooks();

    /*
    טיפול בהצעות שפג תוקפן.

    אם המשתמש הראשון לא הזמין בזמן,
    ההצעה תעבור למשתמש הבא בתור.
    */
    await waitingListService.processExpiredOffers();
  } catch (error) {
    /*
    המתזמן פועל ברקע.

    לכן שגיאה במחזור התחזוקה נרשמת
    בקונסול אך אינה מפילה את השרת.
    */
    console.error("Waiting-list maintenance failed:", error);
  } finally {
    /*
    שחרור נעילת המחזור גם לאחר שגיאה,
    כדי שהמחזור הבא יוכל לפעול.
    */
    isRunning = false;
  }
}

/*
---------------------------------------------------------
startWaitingListScheduler

תפקיד:
מפעילה את מתזמן רשימות ההמתנה.

הפונקציה:
- מונעת יצירת מתזמן כפול.
- מריצה בדיקה ראשונה מיד.
- ממשיכה להריץ בדיקה בכל 60 שניות.

@returns {Object}
מחזירה את מזהה ה-setInterval הפעיל.
---------------------------------------------------------
*/
function startWaitingListScheduler() {
  /*
  אם המתזמן כבר הופעל,
  מחזירים את המתזמן הקיים.
  */
  if (scheduler) {
    return scheduler;
  }

  /*
  הרצה מידית עם הפעלת השרת.

  אין צורך להמתין דקה עד לבדיקה הראשונה.
  */
  runWaitingListMaintenance();

  /*
  הפעלת מחזור התחזוקה פעם בדקה.
  */
  scheduler = setInterval(runWaitingListMaintenance, 60 * 1000);

  /*
  unref מאפשר לתהליך Node להיסגר בצורה תקינה
  אם המתזמן הוא הדבר היחיד שעדיין פעיל.

  סימן השאלה שומר על תאימות לסביבות שבהן
  המתודה אינה קיימת.
  */
  scheduler.unref?.();

  return scheduler;
}

/*
ייצוא הפונקציות:

runWaitingListMaintenance:
שימושי לבדיקה ידנית או לבדיקה אוטומטית.

startWaitingListScheduler:
מופעל מתוך app.js לאחר שהשרת התחבר למסד.
*/
module.exports = {
  runWaitingListMaintenance,
  startWaitingListScheduler,
};
